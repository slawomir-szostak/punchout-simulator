#!/usr/bin/env node
// Regenerates src/server/cxml/code-lists.ts from the published code lists.
//
//   node scripts/gen-code-lists.mjs <dir>
//
// <dir> holds:
//   list-one.xml  ISO 4217 current currency & funds codes, from the maintenance
//                 agency (six-group.com → "List one")
//   rec20.json    UN/CEFACT Recommendation 20 units of measure, and
//   rec21.csv     UN/CEFACT Recommendation 21 package codes, both from
//                 github.com/uncefact/vocab-codes (CLR/Rec20/current, CLR/Rec21/current)
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = process.argv[2];
if (!dir) {
  console.error("usage: gen-code-lists.mjs <dir with list-one.xml, rec20.json, rec21.csv>");
  process.exit(1);
}
const read = (name) => readFileSync(join(dir, name), "utf8");
const CODE = /^[A-Z0-9]{2,3}$/;
const sorted = (set) => [...set].sort().join(" ");

const iso = read("list-one.xml");
const published = /Pblshd="([^"]+)"/.exec(iso)?.[1] ?? "unknown";
const currencies = new Set([...iso.matchAll(/<Ccy>([A-Z]{3})<\/Ccy>/g)].map((m) => m[1]));

// Rec 20 status: X = marked as deleted, D = deprecated; anything else is in use.
const units = new Set();
const withdrawn = new Set();
for (const v of JSON.parse(read("rec20.json")).values) {
  if (!CODE.test(v.CommonCode)) throw new Error(`unexpected Rec 20 code "${v.CommonCode}"`);
  (v.Status === "X" || v.Status === "D" ? withdrawn : units).add(v.CommonCode);
}

// Rec 21: Status,Code,… — a package code is used as a unit with an "X" in front.
const packages = new Set();
for (const line of read("rec21.csv").split(/\r?\n/).slice(1)) {
  const [status, code] = line.split(",");
  if (!code) continue;
  if (!CODE.test(code)) throw new Error(`unexpected Rec 21 code "${code}"`);
  if (status !== "X") packages.add(code);
}

if (currencies.size < 150 || units.size < 1500 || packages.size < 300) throw new Error("a list came out too short");

const file = `// GENERATED by scripts/gen-code-lists.mjs — do not edit.
//
// Codes separated by spaces.

/** ISO 4217 currency and funds codes in use ("List one", published ${published}). */
export const CURRENCY_CODES = ${JSON.stringify(sorted(currencies))};
export const CURRENCY_LIST_DATE = ${JSON.stringify(published)};

/** UN/CEFACT Recommendation 20 unit-of-measure common codes in use. */
export const UNIT_CODES = ${JSON.stringify(sorted(units))};

/** Recommendation 20 codes marked as deleted or deprecated. */
export const WITHDRAWN_UNIT_CODES = ${JSON.stringify(sorted(withdrawn))};

/** UN/CEFACT Recommendation 21 package codes; as a unit of measure they carry an "X" prefix (XBX = box). */
export const PACKAGE_CODES = ${JSON.stringify(sorted(packages))};
`;
writeFileSync(new URL("../src/server/cxml/code-lists.ts", import.meta.url), file);
console.error(`${currencies.size} currencies (${published}), ${units.size} units + ${withdrawn.size} withdrawn, ${packages.size} package codes`);
